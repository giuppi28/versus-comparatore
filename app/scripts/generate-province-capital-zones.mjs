// Generates src/config/province-capital-zones.ts from the reviewed comuni dataset
// (supabase/bootstrap/comuni_*.json, read-only). Run from app/:
//   node scripts/generate-province-capital-zones.mjs
// For each province it looks up the capital comune BY NAME inside that province and
// copies its official climate zone (DPR 412/93). Provinces with several capitals use the
// first-named / administrative seat (see CAPITALS below). Fails loudly if a capital is
// missing from the dataset, has no zone, or a province has no entry.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

// province_code -> capital comune name (as spelled in the dataset).
// Multi-capital provinces: BT Barletta (first of Barletta-Andria-Trani), MB Monza, PU Pesaro,
// MS Massa, FC Forlì, OT Olbia (first of Olbia-Tempio), OG Lanusei (administrative seat),
// VS Sanluri (first of Sanluri-Villacidro), CI Carbonia (first of Carbonia-Iglesias).
// The dataset has 110 provinces (pre-merge Sardinian provinces OT/OG/VS/CI, no Sud Sardegna).
const CAPITALS = {
  TO: "Torino", VC: "Vercelli", NO: "Novara", CN: "Cuneo", AT: "Asti", AL: "Alessandria",
  BI: "Biella", VB: "Verbania", AO: "Aosta", IM: "Imperia", SV: "Savona", GE: "Genova",
  SP: "La Spezia", VA: "Varese", CO: "Como", SO: "Sondrio", MI: "Milano", BG: "Bergamo",
  BS: "Brescia", PV: "Pavia", CR: "Cremona", MN: "Mantova", LC: "Lecco", LO: "Lodi",
  MB: "Monza", BZ: "Bolzano", TN: "Trento", VR: "Verona", VI: "Vicenza", BL: "Belluno",
  TV: "Treviso", VE: "Venezia", PD: "Padova", RO: "Rovigo", UD: "Udine", GO: "Gorizia",
  TS: "Trieste", PN: "Pordenone", PC: "Piacenza", PR: "Parma", RE: "Reggio nell'Emilia",
  MO: "Modena", BO: "Bologna", FE: "Ferrara", RA: "Ravenna", FC: "Forlì", RN: "Rimini",
  PU: "Pesaro", AN: "Ancona", MC: "Macerata", AP: "Ascoli Piceno", FM: "Fermo",
  MS: "Massa", LU: "Lucca", PT: "Pistoia", FI: "Firenze", LI: "Livorno", PI: "Pisa",
  AR: "Arezzo", SI: "Siena", GR: "Grosseto", PO: "Prato", PG: "Perugia", TR: "Terni",
  VT: "Viterbo", RI: "Rieti", RM: "Roma", LT: "Latina", FR: "Frosinone", CE: "Caserta",
  BN: "Benevento", NA: "Napoli", AV: "Avellino", SA: "Salerno", AQ: "L'Aquila",
  TE: "Teramo", PE: "Pescara", CH: "Chieti", CB: "Campobasso", IS: "Isernia",
  FG: "Foggia", BA: "Bari", TA: "Taranto", BR: "Brindisi", LE: "Lecce", BT: "Barletta",
  PZ: "Potenza", MT: "Matera", CS: "Cosenza", CZ: "Catanzaro", RC: "Reggio di Calabria",
  KR: "Crotone", VV: "Vibo Valentia", TP: "Trapani", PA: "Palermo", ME: "Messina",
  AG: "Agrigento", CL: "Caltanissetta", EN: "Enna", CT: "Catania", RG: "Ragusa",
  SR: "Siracusa", SS: "Sassari", OT: "Olbia", NU: "Nuoro", OR: "Oristano",
  OG: "Lanusei", VS: "Sanluri", CA: "Cagliari", CI: "Carbonia",
};

const all = [];
for (let i = 1; i <= 9; i++) {
  all.push(...JSON.parse(readFileSync(join(root, "supabase/bootstrap", `comuni_0${i}.json`), "utf8")));
}
const provinces = new Set(all.map((c) => c.province_code));
const errors = [];
for (const p of provinces) if (!CAPITALS[p]) errors.push(`province ${p} has no capital entry`);
const out = {};
for (const [prov, name] of Object.entries(CAPITALS)) {
  if (!provinces.has(prov)) { errors.push(`unknown province ${prov}`); continue; }
  const c = all.find((x) => x.province_code === prov && x.name === name);
  if (!c) { errors.push(`capital "${name}" not found in ${prov}`); continue; }
  if (!/^[A-F]$/.test(c.climate_zone ?? "")) { errors.push(`capital "${name}" (${prov}) has no zone`); continue; }
  out[prov] = { zone: c.climate_zone, name: c.name };
}
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }

const lines = Object.keys(out).sort().map((p) => `  ${p}: "${out[p].zone}", // ${out[p].name}`);
const ts = `/**
 * GENERATED by scripts/generate-province-capital-zones.mjs from the comuni dataset
 * (supabase/bootstrap/comuni_*.json). Do not edit by hand; re-run the script.
 *
 * Climate zone (DPR 412/93) of each province's capital comune, keyed by province_code.
 * Used internally as the fallback for comuni whose own zone is unknown (nothing is shown
 * to the user). Provinces with several capitals use the first-named seat: BT Barletta,
 * MB Monza, PU Pesaro, MS Massa, FC Forlì, OT Olbia, OG Lanusei, VS Sanluri, CI Carbonia.
 */
import type { ClimateZone } from "@/lib/data/types";

export const PROVINCE_CAPITAL_ZONES: Readonly<Record<string, ClimateZone>> = {
${lines.join("\n")}
};
`;
writeFileSync(join(root, "src/config/province-capital-zones.ts"), ts);
console.log(`wrote ${lines.length} provinces`);
